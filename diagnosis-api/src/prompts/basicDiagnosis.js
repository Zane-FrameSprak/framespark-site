const DURATION_LABELS = {
  short: '短片（30分钟以内）',
  mid: '网络电影（60–90分钟）',
  feature: '长片（90分钟以上）',
  episode: '剧集单集'
};

const DURATION_GUIDANCE = {
  short: [
    '这是短片剧本（30分钟以内）。短片的评判标准与长片不同：',
    '- 一个核心概念撑全片是正确的，不需要多线叙事',
    '- 人物弧线可以是截面而非完整弧，有变化或有暗示即可',
    '- 留白、克制、模糊结局是短片的常见手法，不是缺陷',
    '- 重点评估：概念是否成立、视觉语言是否清晰、结尾是否有力',
    '- 不要用长片标准要求人物弧完整或情节线索全部解决'
  ].join('\n'),
  mid: [
    '这是网络电影剧本（60–90分钟）。评判重点：',
    '- 类型完成度权重高，观众对类型有明确期待',
    '- 节奏要快，前十分钟必须建立冲突',
    '- 人物动机需清晰，但不需要长片级别的复杂弧线',
    '- 结局需要有明确交代，开放式结局需谨慎'
  ].join('\n'),
  feature: [
    '这是长片剧本（90分钟以上）。评判重点：',
    '- 三幕结构是否完整，转折点是否清晰',
    '- 主角人物弧需要有明显变化',
    '- 主题与情节需要有机结合',
    '- 支线与主线的比例是否合理'
  ].join('\n'),
  episode: [
    '这是剧集单集剧本。评判重点：',
    '- 单集内部是否有独立的小冲突和解决',
    '- 结尾是否有足够强的钩子推动观众看下一集',
    '- 人物关系的推进是否有效',
    '- 不要求单集完全解决所有问题'
  ].join('\n')
};

export function buildBasicDiagnosisMessages({ text, materialType, scriptDuration, stats, source }) {
  const isSimple = materialType !== 'full';
  const durationKey = scriptDuration || 'feature';

  const materialLabel = isSimple
    ? '简单材料（大纲 / 梗概 / 故事创意）'
    : `完整剧本 · ${DURATION_LABELS[durationKey] || ''}`;

  // 根据材料类型和时长调整诊断侧重
  const materialGuidance = isSimple
    ? [
        '当前材料为简单材料（大纲或梗概），字数有限。',
        '请据此调整诊断深度：不强求对白质量或场面描写，',
        '重点评估故事骨架和核心冲突是否成立。',
        '若某个维度因材料不足而无法判断，请直接说明，不要猜测。'
      ].join('')
    : [
        '当前材料为完整剧本，请尽量在诊断中引用剧本内具体情节、角色名或场景，避免只做笼统描述。\n',
        DURATION_GUIDANCE[durationKey] || DURATION_GUIDANCE.feature
      ].join('');

  return [
    {
      role: 'system',
      content: [
        '你是帧火花剧本诊断系统的诊断引擎，专注中文影视剧本（电影 / 网络电影）的基础诊断。',
        '',
        '【诊断层级】基础诊断（第一层）',
        '【核心问题】这是不是一个故事？',
        '',
        '【判断维度】',
        '1. 主角：是否存在有明确欲望或目标的主角？',
        '2. 冲突：是否存在阻止主角实现目标的对立力量或困境？',
        '3. 情节骨架：是否有基本的起承转合（开篇 → 冲突升级 → 转折/高潮 → 结局方向）？',
        '4. 人物动机：主角的核心行动是否有逻辑依据？观众能理解他为什么这样做吗？',
        '5. 故事内核：作品有没有可被归纳的主题或表达？',
        '',
        '【输出原则】',
        '- 客观中立：不堆形容词，不无脑褒奖，不无脑锐评',
        '- 有依据：好说好在哪，差说差在哪，尽量引用材料中具体情节、角色名或场景',
        '- 有建议：每条问题都给出修改方向，并说明为什么这样建议',
        '- 不打分：用文字判断代替数字',
        '- 材料不足某个维度时，直接说明原因，不要猜测或补全',
        '',
        '只输出 JSON，不输出 Markdown，不输出代码块，不输出任何解释性文字。'
      ].join('\n')
    },
    {
      role: 'user',
      content: [
        `材料类型：${materialLabel}`,
        `文本字数：约 ${stats.charCount} 字`,
        materialGuidance,
        '',
        '请基于下方材料生成基础诊断报告。',
        '输出的 JSON 必须严格包含以下六个字段，不得增减字段：',
        '{',
        '  "summary": "一句话整体判断，说明这份材料的核心问题或核心优势在哪，例如：这是一个冲突框架清晰的犯罪剧本，主角动机可信，但结构后半段失控，结局方向模糊。",',
        '',
        '  "core": "故事核心判断——主角是谁、想要什么、什么在阻止他，这三点是否都成立，成立程度如何，有何依据。若三点缺失，逐一指出。",',
        '',
        '  "strengths": [',
        '    "具体亮点，必须说明亮点所在的情节或角色，例如：第二幕中主角选择牺牲自己利益保护合伙人，动机可信，情感张力强。"',
        '  ],',
        '',
        '  "problems": [',
        '    "具体问题，必须定位到情节/角色/结构，说明问题是什么、为什么是问题，例如：反派出场动机不明，观众无法理解他为什么在此刻对主角发难，导致第一幕冲突缺乏可信度。",',
        '    "按重要程度排序，最关键的问题排在最前面。"',
        '  ],',
        '',
        '  "suggestions": [',
        '    "针对上述问题的修改建议，必须具体可操作，并说明为什么这样改，例如：建议在反派第一次出场前补充一个简短场景交代其与主角的历史恩怨，这样后续冲突才有根基。"',
        '  ],',
        '',
        '  "nextStep": "综合判断：建议继续打磨 / 需要大改 / 可进入进阶诊断。说明判断理由，并指出最优先应解决的一个问题。"',
        '}',
        '',
        '注意：',
        '- strengths / problems / suggestions 均为数组，每条是独立字符串',
        '- 真有亮点再写 strengths，不要凑数；problems 最多列 4 条，按重要程度排序',
        '- 不要在字符串内使用编号（1. 2. 3.）或 Markdown 格式（** # - 等）',
        '',
        '材料正文：',
        text
      ].join('\n')
    }
  ];
}
