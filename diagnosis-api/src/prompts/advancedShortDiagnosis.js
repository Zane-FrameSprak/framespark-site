// ─── 主函数 ────────────────────────────────────────────────────
export function buildAdvancedShortDiagnosisMessages({ text, stats, source }) {
  return [
    {
      role: 'system',
      content: SYSTEM_ADVANCED_SHORT
    },
    {
      role: 'user',
      content: [
        '材料类型：短片剧本（进阶诊断）',
        `文本字数：约 ${stats.charCount} 字`,
        MATERIAL_GUIDANCE_ADVANCED_SHORT,
        '',
        OUTPUT_FORMAT_ADVANCED_SHORT,
        '',
        '材料正文：',
        text
      ].join('\n')
    }
  ];
}
