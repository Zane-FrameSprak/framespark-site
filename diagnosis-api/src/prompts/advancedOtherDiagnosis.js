// ─── 主函数 ────────────────────────────────────────────────────
export function buildAdvancedOtherDiagnosisMessages({ text, targetFormat, materialForm, stats, source }) {
  const targetLine = targetFormat ? [`目标作品方向：${targetFormat}`] : [];
  const materialFormLine = materialForm ? [`第零层识别材料形态：${materialForm}`] : [];

  return [
    {
      role: 'system',
      content: SYSTEM_ADVANCED_OTHER
    },
    {
      role: 'user',
      content: [
        '材料类型：其他创意材料（进阶诊断）',
        ...targetLine,
        ...materialFormLine,
        `文本字数：约 ${stats.charCount} 字`,
        MATERIAL_GUIDANCE_ADVANCED_OTHER,
        '',
        OUTPUT_FORMAT_ADVANCED_OTHER,
        '',
        '材料正文：',
        text
      ].join('\n')
    }
  ];
}
