export function buildAdvancedOtherDiagnosisMessages({ text, stats, source }) {
  return [
    {
      role: 'system',
      content: SYSTEM_ADVANCED_OTHER
    },
    {
      role: 'user',
      content: [
        '材料类型：其他创意材料（进阶诊断）',
        `文本字数：约 ${stats.charCount} 字`,
        MATERIAL_GUIDANCE_ADVANCED_OTHER,
        '',
        OUTPUT_FORMAT_ADVANCED_OTHER,
        '',
        '材料正文：',
        text
      ].join('\n')
    }
  ];
}
